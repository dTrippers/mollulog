CREATE TABLE ocr_result_artifacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL UNIQUE,
  job_uid text NOT NULL,
  attempt_uid text NOT NULL,
  task_uid text NOT NULL,
  generation integer NOT NULL,
  student_uid text NOT NULL,
  source_frame integer NOT NULL,
  timestamp_ms integer NOT NULL,
  object_key text NOT NULL UNIQUE,
  content_type text NOT NULL,
  byte_size integer NOT NULL,
  sha256 text NOT NULL,
  width integer NOT NULL,
  height integer NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  purge_after timestamptz NOT NULL,
  deleted_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX ocr_result_artifacts_attempt_student_uidx
  ON ocr_result_artifacts (attempt_uid, student_uid);
CREATE INDEX ocr_result_artifacts_job_generation_status_idx
  ON ocr_result_artifacts (job_uid, generation, status);
CREATE INDEX ocr_result_artifacts_status_purge_idx
  ON ocr_result_artifacts (status, purge_after);
