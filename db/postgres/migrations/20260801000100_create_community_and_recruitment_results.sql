CREATE TABLE community_posts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL,
  user_id integer NOT NULL,
  post_type text NOT NULL,
  origin text NOT NULL DEFAULT 'user',
  title text,
  visibility text NOT NULL DEFAULT 'public',
  pinned boolean NOT NULL DEFAULT false,
  subject_student_uid text,
  subject_content_uid text,
  subject_raid_type text,
  subject_season_index integer,
  blocks jsonb NOT NULL DEFAULT '[]'::jsonb,
  source_type text,
  source_uid text,
  source_id integer,
  source_name text,
  source_url text,
  source_metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  migrated_at timestamptz,
  display_at timestamptz,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);

CREATE UNIQUE INDEX community_posts_uid_uidx ON community_posts (uid);
CREATE UNIQUE INDEX community_posts_source_uidx ON community_posts (source_type, source_uid);
CREATE INDEX community_posts_post_type_idx ON community_posts (post_type);
CREATE INDEX community_posts_user_id_idx ON community_posts (user_id);
CREATE INDEX community_posts_subject_student_uid_idx ON community_posts (subject_student_uid);
CREATE INDEX community_posts_subject_content_uid_idx ON community_posts (subject_content_uid);
CREATE INDEX community_posts_subject_raid_idx ON community_posts (subject_raid_type, subject_season_index);
CREATE INDEX community_posts_feed_order_idx ON community_posts ((coalesce(display_at, created_at)) DESC, id DESC);
CREATE INDEX community_posts_updated_at_idx ON community_posts (updated_at DESC, created_at DESC);
CREATE UNIQUE INDEX community_posts_student_review_per_user_uidx
  ON community_posts (user_id, subject_student_uid)
  WHERE post_type = 'student_review';

CREATE TABLE community_comments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL,
  post_uid text NOT NULL,
  user_id integer NOT NULL,
  parent_uid text NOT NULL,
  body text NOT NULL,
  visibility text NOT NULL DEFAULT 'public',
  source_type text,
  source_uid text,
  source_id integer,
  migrated_at timestamptz,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);

CREATE UNIQUE INDEX community_comments_uid_uidx ON community_comments (uid);
CREATE UNIQUE INDEX community_comments_source_uidx ON community_comments (source_type, source_uid);
CREATE INDEX community_comments_post_uid_idx ON community_comments (post_uid);
CREATE INDEX community_comments_parent_uid_idx ON community_comments (parent_uid);
CREATE INDEX community_comments_created_at_idx ON community_comments (post_uid, created_at, id);

CREATE TABLE community_post_likes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL,
  post_uid text NOT NULL,
  user_id integer NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE UNIQUE INDEX community_post_likes_uid_uidx ON community_post_likes (uid);
CREATE UNIQUE INDEX community_post_likes_post_uid_user_id_uidx ON community_post_likes (post_uid, user_id);
CREATE INDEX community_post_likes_post_uid_idx ON community_post_likes (post_uid);

CREATE TABLE community_post_tags (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL,
  post_uid text NOT NULL,
  student_uid text NOT NULL,
  tag_value text NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE UNIQUE INDEX community_post_tags_uid_uidx ON community_post_tags (uid);
CREATE INDEX community_post_tags_post_uid_idx ON community_post_tags (post_uid);
CREATE INDEX community_post_tags_student_uid_idx ON community_post_tags (student_uid);
CREATE INDEX community_post_tags_tag_value_idx ON community_post_tags (tag_value);

CREATE TABLE recruitment_results (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL,
  user_id integer NOT NULL,
  recruitment_group_uid text NOT NULL,
  content_uid text,
  completed_at timestamptz,
  recruited_students jsonb NOT NULL DEFAULT '[]'::jsonb,
  exchanged_students jsonb NOT NULL DEFAULT '[]'::jsonb,
  tier3_count integer,
  trial integer,
  raw_result text,
  comment_post_uid text,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);

CREATE UNIQUE INDEX recruitment_results_uid_uidx ON recruitment_results (uid);
CREATE UNIQUE INDEX recruitment_results_user_group_uidx ON recruitment_results (user_id, recruitment_group_uid);
CREATE INDEX recruitment_results_user_id_idx ON recruitment_results (user_id);
CREATE INDEX recruitment_results_content_uid_idx ON recruitment_results (content_uid);
CREATE INDEX recruitment_results_comment_post_uid_idx ON recruitment_results (comment_post_uid);
