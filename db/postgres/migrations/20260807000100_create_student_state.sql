CREATE TABLE sync_drafts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL,
  user_id integer NOT NULL,
  api_key_uid text,
  source text NOT NULL DEFAULT 'connect',
  source_ref text,
  type text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  tool_name text,
  tool_version text,
  catalog_version text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  applied_at timestamptz,
  expires_at timestamptz
);
CREATE UNIQUE INDEX sync_drafts_uid_uidx ON sync_drafts (uid);
CREATE UNIQUE INDEX sync_drafts_user_source_ref_uidx ON sync_drafts (user_id, source, source_ref) WHERE source_ref IS NOT NULL;
CREATE INDEX sync_drafts_user_status_idx ON sync_drafts (user_id, status);

CREATE TABLE sync_draft_entries (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL,
  draft_uid text NOT NULL,
  entry_key text NOT NULL,
  value integer NOT NULL,
  value_json text,
  meta text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX sync_draft_entries_uid_uidx ON sync_draft_entries (uid);
CREATE UNIQUE INDEX sync_draft_entries_draft_entry_uidx ON sync_draft_entries (draft_uid, entry_key);
CREATE INDEX sync_draft_entries_draft_uid_idx ON sync_draft_entries (draft_uid, id);

