CREATE TABLE recruited_students (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL,
  user_id integer NOT NULL,
  student_uid text NOT NULL,
  tier integer NOT NULL,
  level integer,
  skill_ex integer,
  skill_normal integer,
  skill_enhanced integer,
  skill_sub integer,
  equip1 integer,
  equip2 integer,
  equip3 integer,
  equip_special integer,
  weapon_level integer,
  ability_hp integer,
  ability_atk integer,
  ability_heal integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX recruited_students_uid_uidx ON recruited_students (uid);
CREATE UNIQUE INDEX recruited_students_user_student_uidx ON recruited_students (user_id, student_uid);
CREATE INDEX recruited_students_user_id_idx ON recruited_students (user_id);
CREATE INDEX recruited_students_student_uid_idx ON recruited_students (student_uid);

