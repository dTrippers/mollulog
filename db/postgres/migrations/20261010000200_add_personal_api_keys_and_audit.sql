ALTER TABLE student_state_audits
  ADD COLUMN api_key_uid text,
  ADD COLUMN api_key_name text;

CREATE TABLE api_keys (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL,
  user_id integer NOT NULL,
  name text NOT NULL,
  key_hash text NOT NULL,
  key_prefix text NOT NULL,
  read_scope boolean NOT NULL DEFAULT false,
  write_scope boolean NOT NULL DEFAULT false,
  expires_at timestamptz NOT NULL,
  last_used_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX api_keys_uid_uidx ON api_keys (uid);
CREATE UNIQUE INDEX api_keys_key_hash_uidx ON api_keys (key_hash);
CREATE INDEX api_keys_user_id_idx ON api_keys (user_id, created_at DESC);

CREATE TABLE api_key_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL,
  api_key_uid text NOT NULL,
  api_key_name text NOT NULL,
  action text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX api_key_events_user_created_idx ON api_key_events (user_id, created_at DESC);

CREATE TABLE api_write_quotas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL,
  window_started_at timestamptz NOT NULL,
  request_count integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX api_write_quotas_user_id_uidx ON api_write_quotas (user_id);
