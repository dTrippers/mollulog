CREATE TABLE oauth_applications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id integer NOT NULL,
  uid text NOT NULL,
  name text NOT NULL,
  client_id text NOT NULL,
  client_secret_hash text NOT NULL,
  client_secret_prefix text NOT NULL,
  redirect_uris text[] NOT NULL,
  scopes text[] NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  client_secret_issued_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE UNIQUE INDEX oauth_applications_uid_uidx ON oauth_applications (uid);
CREATE UNIQUE INDEX oauth_applications_client_id_uidx ON oauth_applications (client_id);
CREATE INDEX oauth_applications_owner_created_idx ON oauth_applications (owner_user_id, created_at DESC);

CREATE TABLE oauth_grants (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id integer NOT NULL,
  user_id integer NOT NULL,
  subject text NOT NULL,
  scopes text[] NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  disconnected_at timestamptz
);
CREATE UNIQUE INDEX oauth_grants_subject_uidx ON oauth_grants (subject);
CREATE UNIQUE INDEX oauth_grants_active_user_application_uidx
  ON oauth_grants (user_id, application_id) WHERE disconnected_at IS NULL;
CREATE INDEX oauth_grants_user_idx ON oauth_grants (user_id, created_at DESC);

CREATE TABLE oauth_authorization_codes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code_hash text NOT NULL,
  application_id integer NOT NULL,
  user_id integer NOT NULL,
  grant_id integer NOT NULL,
  redirect_uri text NOT NULL,
  scopes text[] NOT NULL,
  code_challenge text,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  used_at timestamptz
);
CREATE UNIQUE INDEX oauth_authorization_codes_hash_uidx ON oauth_authorization_codes (code_hash);
CREATE INDEX oauth_authorization_codes_expiry_idx ON oauth_authorization_codes (expires_at);

CREATE TABLE oauth_access_tokens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash text NOT NULL,
  token_prefix text NOT NULL,
  application_id integer NOT NULL,
  user_id integer NOT NULL,
  grant_id integer NOT NULL,
  scopes text[] NOT NULL,
  issued_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  last_used_at timestamptz
);
CREATE UNIQUE INDEX oauth_access_tokens_hash_uidx ON oauth_access_tokens (token_hash);
CREATE INDEX oauth_access_tokens_grant_idx ON oauth_access_tokens (grant_id, last_used_at DESC);

CREATE TABLE oauth_connection_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL,
  grant_id integer NOT NULL,
  application_uid text NOT NULL,
  application_name text NOT NULL,
  action text NOT NULL,
  scopes text[] NOT NULL,
  disconnect_reason text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX oauth_connection_events_user_created_idx ON oauth_connection_events (user_id, created_at DESC);

