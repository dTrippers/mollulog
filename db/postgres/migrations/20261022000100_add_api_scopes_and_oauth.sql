ALTER TABLE api_keys ADD COLUMN scopes text[] NOT NULL DEFAULT '{}';
UPDATE api_keys
   SET scopes = (CASE
     WHEN write_scope THEN ARRAY['students:read', 'students:write']::text[]
     WHEN read_scope THEN ARRAY['students:read']::text[]
     ELSE ARRAY[]::text[]
   END);

CREATE FUNCTION sync_api_key_scopes_from_legacy_columns() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF cardinality(NEW.scopes) = 0 THEN
    NEW.scopes := CASE
      WHEN NEW.write_scope THEN ARRAY['students:read', 'students:write']::text[]
      WHEN NEW.read_scope THEN ARRAY['students:read']::text[]
      ELSE ARRAY[]::text[]
    END;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER api_keys_sync_legacy_scopes_before_insert
BEFORE INSERT ON api_keys
FOR EACH ROW
EXECUTE FUNCTION sync_api_key_scopes_from_legacy_columns();

