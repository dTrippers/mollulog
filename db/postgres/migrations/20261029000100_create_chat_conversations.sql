CREATE TABLE chat_conversations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL UNIQUE,
  sensei_id integer NOT NULL,
  title text NOT NULL,
  last_message_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX chat_conversations_sensei_last_message_idx ON chat_conversations (sensei_id, last_message_at DESC);

CREATE TABLE chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL UNIQUE,
  conversation_id bigint NOT NULL REFERENCES chat_conversations(id) ON DELETE CASCADE,
  seq integer NOT NULL,
  question text NOT NULL,
  personal_mode boolean NOT NULL,
  status text NOT NULL,
  answer jsonb,
  failure_code text,
  run_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);

CREATE UNIQUE INDEX chat_messages_conversation_seq_uidx ON chat_messages (conversation_id, seq);
