-- Recruitment ticket cards an operator chose to show on the web 상품 / 패키지 › 모집권 tab. Only shown cards have a
-- row. A product card is (product_uid, item_uid); a card for tickets outside products has one row per item_uid with
-- product_uid NULL, and shows when any of its items has a row.
CREATE TABLE recruit_tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_uid text,
  item_uid text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX recruit_tickets_product_item_uidx ON recruit_tickets (product_uid, item_uid)
  WHERE product_uid IS NOT NULL;
CREATE UNIQUE INDEX recruit_tickets_item_uidx ON recruit_tickets (item_uid)
  WHERE product_uid IS NULL;
