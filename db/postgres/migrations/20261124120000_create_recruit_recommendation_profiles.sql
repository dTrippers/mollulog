-- The goal a Sensei chose on 모집 추천 (top = 최상위권, platinum = 플래티넘, newbie = 뉴비). One row per user, written
-- when the user first picks a goal; a user without a row has not chosen one. Guests keep the goal in their browser.
CREATE TABLE recruit_recommendation_profiles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL,
  goal text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX recruit_recommendation_profiles_user_id_uidx ON recruit_recommendation_profiles (user_id);
