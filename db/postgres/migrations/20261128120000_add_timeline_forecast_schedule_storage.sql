-- Forecast (미확정) Korean-server schedules are kept in MolluLog itself, because BAQL will keep only schedules that are
-- in the game client or officially announced.

-- The JP raid season a raid row corresponds to, by its client values (BAQL `raidSchedule.jpSchedule.raidType` and
-- `.seasonIndex`). A GL season number is a prediction until the season is confirmed, so the sync finds a raid row by
-- this pair, never by its GL schedule uid. Null on rows that are not raids or whose JP season is not known yet.
ALTER TABLE timeline_contents ADD COLUMN jp_raid_type text;
ALTER TABLE timeline_contents ADD COLUMN jp_raid_season_index integer;

-- MolluLog's own copy of a pickup recruitment group. A timeline row finds its group through
-- `timeline_contents.recruitment_group_uid` = `uid`. The group's period can differ from the period of that row.
CREATE TABLE timeline_recruitment_groups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid text NOT NULL,
  start_at timestamptz NOT NULL,
  end_at timestamptz,
  recruitment_type text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX timeline_recruitment_groups_uid_uidx ON timeline_recruitment_groups (uid);

-- The recruitments of a group, in the source's order (`id` ascending). `student_uid` is null for a student MolluLog
-- does not know yet; `student_name` is always kept.
CREATE TABLE timeline_recruitments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recruitment_group_uid text NOT NULL REFERENCES timeline_recruitment_groups (uid),
  student_uid text,
  student_name text NOT NULL,
  recruitment_type text NOT NULL,
  pickup boolean NOT NULL,
  rerun boolean NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX timeline_recruitments_recruitment_group_uid_idx ON timeline_recruitments (recruitment_group_uid, id);
