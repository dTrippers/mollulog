-- Students a timeline content is expected to bring to the Korean server before official confirmation:
-- kind `pickup` (featured in the content's recruitment, with recruitment_type usual, limited, or fes) or
-- `given` (handed out by the content, recruitment_type null). student_uid is the BAQL student uid and stays
-- null until the student is in the JP client; student_name is the name the operator entered.
CREATE TABLE timeline_content_forecast_students (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  timeline_content_uid text NOT NULL,
  kind text NOT NULL,
  student_uid text,
  student_name text NOT NULL,
  recruitment_type text,
  rerun boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX timeline_content_forecast_students_content_uid_idx
  ON timeline_content_forecast_students (timeline_content_uid);
CREATE UNIQUE INDEX timeline_content_forecast_students_content_student_uidx
  ON timeline_content_forecast_students (timeline_content_uid, student_uid)
  WHERE student_uid IS NOT NULL;
