-- The recruitment banner sets shown on a timeline content, one row per set. A timeline content can run several sets,
-- each with its own period. recruitment_group_uid set: a confirmed group that exists in BAQL (`recruitment_groups.uid`),
-- whose period and students BAQL owns; student_uids limits it to those students on this timeline content (null means
-- every student of the group). recruitment_group_uid null: a forecast group that exists only in MolluLog, whose period
-- is start_at/end_at and whose students are the timeline_content_forecast_students rows that point to it.
CREATE TABLE timeline_content_recruitment_groups (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  timeline_content_uid text NOT NULL,
  recruitment_group_uid text,
  start_at timestamptz,
  end_at timestamptz,
  student_uids text[],
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX timeline_content_recruitment_groups_content_uid_idx
  ON timeline_content_recruitment_groups (timeline_content_uid);
CREATE INDEX timeline_content_recruitment_groups_group_uid_idx
  ON timeline_content_recruitment_groups (recruitment_group_uid)
  WHERE recruitment_group_uid IS NOT NULL;
CREATE UNIQUE INDEX timeline_content_recruitment_groups_content_group_uidx
  ON timeline_content_recruitment_groups (timeline_content_uid, recruitment_group_uid)
  WHERE recruitment_group_uid IS NOT NULL;

-- A forecast student now belongs to a forecast banner set: kind `recruitment` sets
-- timeline_content_recruitment_group_id; kind `given` (handed out by the timeline content itself) leaves it and
-- recruitment_type null. pickup has the meaning of BAQL `recruitments.pickup`; false is a fes pool student.
ALTER TABLE timeline_content_forecast_students
  ADD COLUMN timeline_content_recruitment_group_id integer
    REFERENCES timeline_content_recruitment_groups (id) ON DELETE CASCADE;
ALTER TABLE timeline_content_forecast_students
  ADD COLUMN pickup boolean NOT NULL DEFAULT true;

DROP INDEX timeline_content_forecast_students_content_student_uidx;
CREATE UNIQUE INDEX timeline_content_forecast_students_group_student_uidx
  ON timeline_content_forecast_students (timeline_content_recruitment_group_id, student_uid)
  WHERE timeline_content_recruitment_group_id IS NOT NULL AND student_uid IS NOT NULL;
CREATE UNIQUE INDEX timeline_content_forecast_students_given_student_uidx
  ON timeline_content_forecast_students (timeline_content_uid, student_uid)
  WHERE timeline_content_recruitment_group_id IS NULL AND student_uid IS NOT NULL;
CREATE INDEX timeline_content_forecast_students_group_id_idx
  ON timeline_content_forecast_students (timeline_content_recruitment_group_id);
