import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "@jest/globals";
import { Client } from "pg";
import {
  completePostgresContentOpinionClassification,
  failPostgresContentOpinionClassification,
  updatePostgresContentOpinion,
} from "~/db/postgres/community";

const describeDatabase = process.env.MOLLULOG_CLASSIFICATION_POSTGRES === "1" ? describe : describe.skip;
const schema = `opinion_test_${randomUUID().replaceAll("-", "")}`;
const migration = readFileSync(
  resolve("db/postgres/migrations/20261024000100_simplify_recruitment_classification.sql"),
  "utf8",
);
const env = {} as Env;
const options = {
  createClient: () => new Client({ options: `-c search_path=${schema}`, connectionTimeoutMillis: 5000 }),
};
let admin: Client;

describeDatabase("recruitment classification on PostgreSQL", () => {
  beforeAll(async () => {
    admin = new Client({ connectionTimeoutMillis: 5000 });
    await admin.connect();
    await admin.query(`CREATE SCHEMA ${schema}`);
    await admin.query(`SET search_path TO ${schema}`);
    await admin.query(`CREATE TABLE community_posts (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, uid text UNIQUE NOT NULL,
      subject_content_uid text NOT NULL DEFAULT 'content-1', user_id integer NOT NULL, post_type text NOT NULL, visibility text NOT NULL DEFAULT 'public',
      blocks jsonb NOT NULL, created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
    );
    CREATE TABLE community_post_recruitment_opinions (
      post_uid text, recruitment_period_start_at timestamptz,
      recruitment_opinion_classification_status text, recruitment_opinion_classification text,
      recruitment_opinion_classification_prompt_version text
    );`);
    for (const [uid, status, label, version] of [
      ["manual", "completed", "RESULT_RELATED", "manual"],
      ["auto", "completed", "OTHER", "old"],
      ["failed", "failed", null, "old"],
      ["before", null, null, null],
    ]) {
      await admin.query(
        "INSERT INTO community_posts (uid,user_id,post_type,blocks,created_at,updated_at) VALUES ($1,1,'event_opinion',$2,$3,$3)",
        [
          uid,
          JSON.stringify([{ type: "plaintext", text: "A" }]),
          uid === "before" ? "2026-08-31T00:00:00Z" : "2026-09-02T00:00:00Z",
        ],
      );
      await admin.query("INSERT INTO community_post_recruitment_opinions VALUES ($1,'2026-09-01T00:00:00Z',$2,$3,$4)", [
        uid,
        status,
        label,
        version,
      ]);
    }
    await admin.query("BEGIN");
    try {
      await admin.query(migration);
      await admin.query("COMMIT");
    } catch (error) {
      await admin.query("ROLLBACK");
      throw error;
    }
  });
  afterAll(async () => {
    if (admin) {
      try {
        await admin.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
      } finally {
        await admin.end();
      }
    }
  });
  it("migrates manual corrections, other, failed, and missing states without changing edit times", async () => {
    const { rows } = await admin.query(
      "SELECT uid,recruitment_classification,updated_at::text FROM community_posts ORDER BY uid",
    );
    expect(rows.map((r) => [r.uid, r.recruitment_classification])).toEqual([
      ["auto", "other"],
      ["before", null],
      ["failed", "failed"],
      ["manual", "result"],
    ]);
    expect(rows.find((r) => r.uid === "manual").updated_at).toContain("2026-09-02");
  });
  it("bases edited-opinion eligibility on original creation, including the exact boundary", async () => {
    const start = "2026-09-01T00:00:00Z";
    const eligible = { ...options, recruitmentPeriodStartAt: start };
    await expect(
      updatePostgresContentOpinion(env, 1, "content-1", "before", "edited", "public", eligible),
    ).resolves.toBeNull();
    await admin.query("UPDATE community_posts SET created_at=$1 WHERE uid='auto'", [start]);
    await expect(updatePostgresContentOpinion(env, 1, "content-1", "auto", "A", "public", eligible)).resolves.toEqual({
      postUid: "auto",
      body: "A",
    });
    await expect(
      updatePostgresContentOpinion(env, 2, "content-1", "auto", "unauthorized", "public", eligible),
    ).resolves.toBeNull();
  });
  it("rejects old-body results and prevents a late failure from replacing success", async () => {
    await updatePostgresContentOpinion(env, 1, "content-1", "auto", "B", "public", {
      ...options,
      recruitmentPeriodStartAt: "2026-09-01T00:00:00Z",
    });
    await expect(
      completePostgresContentOpinionClassification(env, { postUid: "auto", body: "A" }, "result", options),
    ).resolves.toBe(false);
    const timeBefore = (await admin.query("SELECT updated_at::text FROM community_posts WHERE uid='auto'")).rows[0]
      .updated_at;
    await expect(
      completePostgresContentOpinionClassification(env, { postUid: "auto", body: "B" }, "other", options),
    ).resolves.toBe(true);
    await expect(failPostgresContentOpinionClassification(env, { postUid: "auto", body: "B" }, options)).resolves.toBe(
      false,
    );
    const row = (
      await admin.query("SELECT recruitment_classification,updated_at::text FROM community_posts WHERE uid='auto'")
    ).rows[0];
    expect(row).toEqual({ recruitment_classification: "other", updated_at: timeBefore });
  });
  it("does not edit an opinion through another content's recruitment period", async () => {
    await expect(
      updatePostgresContentOpinion(env, 1, "another-content", "manual", "changed", "private", options),
    ).resolves.toBeNull();
    const { rows } = await admin.query(
      "SELECT recruitment_classification,blocks,visibility FROM community_posts WHERE uid='manual'",
    );
    expect(rows[0]).toEqual({
      recruitment_classification: "result",
      blocks: [{ type: "plaintext", text: "A" }],
      visibility: "public",
    });
  });
  it("recovers a same-body success after a delayed failure in an A → B → A edit", async () => {
    const eligible = { ...options, recruitmentPeriodStartAt: "2026-09-01T00:00:00Z" };
    for (const body of ["A", "B", "A"])
      await updatePostgresContentOpinion(env, 1, "content-1", "auto", body, "public", eligible);
    await expect(failPostgresContentOpinionClassification(env, { postUid: "auto", body: "B" }, options)).resolves.toBe(
      false,
    );
    await expect(failPostgresContentOpinionClassification(env, { postUid: "auto", body: "A" }, options)).resolves.toBe(
      true,
    );
    await expect(
      completePostgresContentOpinionClassification(env, { postUid: "auto", body: "A" }, "result", options),
    ).resolves.toBe(true);
    await expect(
      completePostgresContentOpinionClassification(env, { postUid: "auto", body: "A" }, "other", options),
    ).resolves.toBe(false);
  });
  it.each([
    ["invalid label", "completed", "UNKNOWN", "valid, eligible"],
    ["in-flight job", "pending", null, "Drain pending"],
  ])("blocks migration of %s instead of inventing a classification", async (_label, status, label, expected) => {
    await admin.query("BEGIN");
    try {
      await admin.query(
        "UPDATE community_post_recruitment_opinions SET recruitment_opinion_classification_status=$1,recruitment_opinion_classification=$2 WHERE post_uid='failed'",
        [status, label],
      );
      await expect(admin.query(migration)).rejects.toThrow(String(expected));
    } finally {
      await admin.query("ROLLBACK");
    }
  });
});
